/**
 * PATCH /api/v1/projects/:id
 */
const updateProject = asyncHandler(async (req, res) => {
  const { id } = req.params;
  const payload = { ...req.body };

  const project = await loadProject(id);
  await assertCanManage(req.user, project.id);

  if (payload.manager_id) {
    const manager = await userModel.findById(payload.manager_id);
    if (!manager) throw ApiError.badRequest('Manajer yang dipilih tidak ditemukan');
  }

  const nextStart = payload.start_date !== undefined ? payload.start_date : project.start_date;
  const nextEnd = payload.end_date !== undefined ? payload.end_date : project.end_date;

  if (nextStart && nextEnd && nextStart > nextEnd) {
    throw ApiError.badRequest('Tanggal selesai tidak boleh lebih awal dari tanggal mulai');
  }

  const affectsProgress =
    payload.status !== undefined ||
    payload.priority !== undefined ||
    payload.start_date !== undefined ||
    payload.end_date !== undefined;

  await projectModel.updateProject(project.id, payload);

  if (affectsProgress) {
    const recalculated = await progressService.recalculateProjectProgress(project.id);
    // An explicitly requested status wins over the status derived from tasks.
    if (payload.status && payload.status !== recalculated.status) {
      await projectModel.updateProject(project.id, { status: payload.status });
    }
  }

  const updated = await projectModel.findByIdWithManager(project.id);

  await activityService.record({
    userId: req.user.id,
    projectId: project.id,
    action: 'project.updated',
    entityType: 'project',
    entityId: project.id,
    description: `${req.user.name} memperbarui proyek ${updated.name}`,
    metadata: { fields: Object.keys(payload) },
  });

  socketService.emitProjectEvent(project.id, 'project:updated', { project: updated });

  return sendSuccess(res, { project: updated }, 'Proyek berhasil diperbarui');
});

