/**
 * Insert a project, regenerating the code when an auto-generated one turns out
 * to be taken (a concurrent request won the race on the unique index).
 *
 * @param {object} data
 * @returns {Promise<{id:number, code:string}>} the new project
 */
async function createProjectWithUniqueCode(data) {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      // eslint-disable-next-line no-await-in-loop
      return await projectModel.createProject(data);
    } catch (error) {
      if (error.code !== 'ER_DUP_ENTRY' || !data.autoGenerated) throw error;
      // eslint-disable-next-line no-await-in-loop
      data.code = await projectModel.generateProjectCode();
    }
  }
  throw ApiError.conflict('Kode proyek tidak dapat dibuat, silakan coba lagi');
}

/**
 * POST /api/v1/projects
 */
const createProject = asyncHandler(async (req, res) => {
  const {
    name,
    code,
    description,
    status,
    priority,
    color,
    budget,
    start_date,
    end_date,
    manager_id,
    template_id,
    include_template_tasks = true,
    include_template_milestones = true,
  } = req.body;

  let template = null;
  if (template_id) {
    template = await templateModel.findTemplateById(template_id);
    if (!template) throw ApiError.badRequest('Template yang dipilih tidak ditemukan');
  }

  let finalCode = code;
  if (finalCode) {
    const existing = await projectModel.findByCode(finalCode);
    if (existing) throw ApiError.conflict('Kode proyek tersebut sudah digunakan');
  } else {
    finalCode = await projectModel.generateProjectCode();
  }

  let managerId = manager_id;
  if (managerId) {
    const manager = await userModel.findById(managerId);
    if (!manager) throw ApiError.badRequest('Manajer yang dipilih tidak ditemukan');
  } else {
    managerId = req.user.id;
  }

  const finalColor = color || (template ? template.color : DEFAULT_PROJECT_COLORS[0]);

  const created = await createProjectWithUniqueCode({
    code: finalCode,
    autoGenerated: !code,
    name,
    description: description || null,
    status,
    priority,
    color: finalColor,
    budget: budget === undefined ? null : budget,
    start_date: start_date || null,
    end_date: end_date || null,
    manager_id: managerId,
    created_by: req.user.id,
    template_id: template ? template.id : null,
  });

  const projectId = created.id;
  finalCode = created.code;

  await projectModel.addMember(projectId, req.user.id, 'owner');

  if (template) {
    await transaction(async (connection) => {
      await templateModel.instantiateTemplateIntoProject(connection, {
        projectId,
        templateId: template.id,
        startDate: start_date,
        creatorId: req.user.id,
        includeMilestones: include_template_milestones !== false,
        includeTasks: include_template_tasks !== false,
      });
    });
    await progressService.recalculateProjectProgress(projectId);
  } else {
    await projectModel.ensureDefaultStatuses(projectId);
  }

  const project = await projectModel.findByIdWithManager(projectId);

  await activityService.record({
    userId: req.user.id,
    projectId,
    action: 'project.created',
    entityType: 'project',
    entityId: projectId,
    description: `${req.user.name} membuat proyek ${name}`,
    metadata: { code: finalCode },
  });

  await notificationService.notifyProjectMembers(projectId, {
    excludeUserId: req.user.id,
    type: 'info',
    title: 'Proyek baru dibuat',
    message: `${req.user.name} membuat proyek ${name}`,
    link: `/projects/${projectId}`,
  });

  socketService.emitProjectEvent(projectId, 'project:created', { project });

  res.status(201);
  return sendSuccess(res, { project }, 'Proyek berhasil dibuat');
});

